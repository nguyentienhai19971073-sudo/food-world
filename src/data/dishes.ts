export const DISHES: Dish[] = [...BASE_DISHES, ...EXTRA_DISHES];

// Ensure constant nameKey & descKey are assigned for logic consistency
DISHES.forEach((d) => {
  if (!d.nameKey) d.nameKey = `dish_${d.id}_name`;
  if (!d.descKey) d.descKey = `dish_${d.id}_desc`;
});

/**
 * Language-specific arrays for all 6 supported locales
 * Maintains constant ID and countryId references for game logic while providing target localized strings
 */
const mapDish = (d: Dish, lang: Language): LocalizedDish => ({
  id: d.id,
  nameKey: d.nameKey || `dish_${d.id}_name`,
  descKey: d.descKey || `dish_${d.id}_desc`,
  name: d.name[lang] || d.name.en || d.id,
  countryId: d.countryId,
  continent: d.continent,
  description: d.description[lang] || d.description.en || '',
  difficulty: d.difficulty,
  iconType: d.iconType,
  tags: d.tags,
});

export const DISHES_BY_LANG: Record<Language, LocalizedDish[]> = {
  en: DISHES.map((d) => mapDish(d, 'en')),
  vi: DISHES.map((d) => mapDish(d, 'vi')),
  ja: DISHES.map((d) => mapDish(d, 'ja')),
  ko: DISHES.map((d) => mapDish(d, 'ko')),
  es: DISHES.map((d) => mapDish(d, 'es')),
  fr: DISHES.map((d) => mapDish(d, 'fr')),
};

export const DISH_MAP = new Map<string, Dish>(DISHES.map((d) => [d.id, d]));

export function getDish(id: string): Dish | undefined {
  return DISH_MAP.get(id);
}

export function getDishesByCountry(countryId: string): Dish[] {
  return DISHES.filter((d) => d.countryId === countryId);
}

export function getDishesByContinent(continent: string): Dish[] {
  if (continent === 'world') return DISHES;
  return DISHES.filter((d) => d.continent === continent);
}

export function getDishesByLanguage(lang: Language): LocalizedDish[] {
  return DISHES_BY_LANG[lang] || DISHES_BY_LANG.en;
}
