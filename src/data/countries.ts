// Ensure constant nameKey is assigned for logic consistency
COUNTRIES.forEach((c) => {
  if (!c.nameKey) {
    c.nameKey = `country_${c.id}_name`;
  }
});

/**
 * Language-specific arrays for all 6 supported locales
 * Maintains constant ID references for game logic while providing target localized strings
 */
const mapCountry = (c: Country, lang: Language): LocalizedCountry => ({
  id: c.id,
  code: c.code,
  nameKey: c.nameKey || `country_${c.id}_name`,
  name: c.name[lang] || c.name.en || c.id,
  continent: c.continent,
  flagEmoji: c.flagEmoji,
  capital: c.capital,
  color: c.color,
});

export const COUNTRIES_BY_LANG: Record<Language, LocalizedCountry[]> = {
  en: COUNTRIES.map((c) => mapCountry(c, 'en')),
  vi: COUNTRIES.map((c) => mapCountry(c, 'vi')),
  ja: COUNTRIES.map((c) => mapCountry(c, 'ja')),
  ko: COUNTRIES.map((c) => mapCountry(c, 'ko')),
  es: COUNTRIES.map((c) => mapCountry(c, 'es')),
  fr: COUNTRIES.map((c) => mapCountry(c, 'fr')),
};

export const COUNTRY_MAP = new Map<string, Country>(COUNTRIES.map((c) => [c.id, c]));

export function getCountry(id: string): Country | undefined {
  return COUNTRY_MAP.get(id);
}

export function getCountriesByLanguage(lang: Language): LocalizedCountry[] {
  return COUNTRIES_BY_LANG[lang] || COUNTRIES_BY_LANG.en;
}
